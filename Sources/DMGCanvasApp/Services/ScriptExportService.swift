import Foundation

public struct ScriptExportService {
    
    /// Generates a standalone, executable bash/zsh build script for CI/CD pipelines
    public static func generateBuildScript(for project: DMGProject) -> String {
        let volName = project.volumeName
        let dmgName = project.outputFileName
        let format = "UDZO"
        let level = 9
        
        let appleScript = AppleScriptGenerator.generateScript(
            for: project,
            volumeName: volName,
            backgroundFileName: "background.tiff"
        )
        
        var script = """
        #!/usr/bin/env bash
        # ==============================================================================
        # Automated DMG Build Script
        # Generated by DMGEKI / DMG Canvas Studio
        # Project: \(project.name)
        # ==============================================================================
        
        set -euo pipefail
        
        # Configuration
        VOLUME_NAME="\(volName)"
        FINAL_DMG="\(dmgName)"
        OUTPUT_DIR="\(project.outputDirectory)"
        TEMP_DMG_NAME="tmp_uncompressed_${RANDOM}.dmg"
        TEMP_DMG="/tmp/${TEMP_DMG_NAME}"
        STAGING_DIR="$(mktemp -d /tmp/dmg_staging_XXXXXX)"
        
        echo "🚀 Starting DMG build for '${VOLUME_NAME}'..."
        
        # Cleanup trap
        cleanup() {
            echo "🧹 Cleaning up temporary mount & files..."
            hdiutil detach "/Volumes/${VOLUME_NAME}" -force 2>/dev/null || true
            rm -f "${TEMP_DMG}" 2>/dev/null || true
            rm -rf "${STAGING_DIR}" 2>/dev/null || true
        }
        trap cleanup EXIT
        
        # 1. Prepare Staging Directory
        echo "📁 Staging payload items..."
        mkdir -p "${STAGING_DIR}"
        
        """
        
        // Items staging
        for item in project.items {
            if item.isApplicationsSymlink {
                script += """
                # Symlink to /Applications
                ln -s /Applications "${STAGING_DIR}/\(item.destinationName)"
                
                """
            } else if !item.sourcePath.isEmpty {
                script += """
                if [ -e "\(item.sourcePath)" ]; then
                    echo "  -> Copying \(item.name)..."
                    cp -R "\(item.sourcePath)" "${STAGING_DIR}/\(item.destinationName)"
                else
                    echo "  ⚠️ Warning: Source path '\(item.sourcePath)' not found!"
                fi
                
                """
            }
        }
        
        // Background image staging
        script += """
        # Setup high-DPI background image
        echo "🎨 Staging background image..."
        mkdir -p "${STAGING_DIR}/.background"
        """
        
        if let bgPath = project.backgroundImagePath, !bgPath.isEmpty {
            script += """
            if [ -f "\(bgPath)" ]; then
                cp "\(bgPath)" "${STAGING_DIR}/.background/background.png"
                tiffutil -cathidpicheck "${STAGING_DIR}/.background/background.png" "${STAGING_DIR}/.background/background.png" -out "${STAGING_DIR}/.background/background.tiff" 2>/dev/null || true
            fi
            
            """
        } else {
            script += """
            python3 -c '
            from PIL import Image, ImageDraw
            w, h = \(Int(project.window.width)), \(Int(project.window.height))
            img1 = Image.new("RGB", (w, h), (238, 240, 244))
            img2 = Image.new("RGB", (w*2, h*2), (238, 240, 244))
            img1.save("${STAGING_DIR}/.background/bg1.tiff")
            img2.save("${STAGING_DIR}/.background/bg2.tiff")
            img2.save("${STAGING_DIR}/.background/background.png")
            ' 2>/dev/null || true
            if [ -f "${STAGING_DIR}/.background/bg1.tiff" ]; then
                tiffutil -cathidpicheck "${STAGING_DIR}/.background/bg1.tiff" "${STAGING_DIR}/.background/bg2.tiff" -out "${STAGING_DIR}/.background/background.tiff" 2>/dev/null || cp "${STAGING_DIR}/.background/background.png" "${STAGING_DIR}/.background/background.tiff"
                rm -f "${STAGING_DIR}/.background/bg1.tiff" "${STAGING_DIR}/.background/bg2.tiff"
            fi
            
            """
        }
        
        // Volume icon
        if let iconPath = project.volumeIconPath, !iconPath.isEmpty {
            script += """
            # Setup Volume Icon in staging
            if [ -f "\(iconPath)" ]; then
                echo "🖼 Setting volume icon..."
                cp "\(iconPath)" "${STAGING_DIR}/.VolumeIcon.icns"
                SetFile -c icnC "${STAGING_DIR}/.VolumeIcon.icns" 2>/dev/null || true
                SetFile -a V "${STAGING_DIR}/.VolumeIcon.icns" 2>/dev/null || true
            fi
            
            """
        }
        
        script += """
        # 2. Calculate Required Disk Size
        DIR_SIZE_KB=$(du -sk "${STAGING_DIR}" | awk '{print $1}')
        DISK_SIZE_MB=$(( (DIR_SIZE_KB / 1024) + 60 ))
        echo "💾 Calculated image size: ${DISK_SIZE_MB} MB"
        
        # 3. Create Temporary Read-Write DMG
        echo "💿 Creating temporary read-write disk image..."
        hdiutil create -size "${DISK_SIZE_MB}m" -fs HFS+ -volname "${VOLUME_NAME}" -ov "${TEMP_DMG}"
        
        # 4. Attach Temporary DMG
        echo "🔌 Mounting temporary image..."
        MOUNT_DEV=$(hdiutil attach -readwrite -noverify -noautoopen "${TEMP_DMG}" | awk 'NR==1{print $1}')
        
        # 5. Copy Files into Mounted Volume
        echo "📋 Copying staging payload into volume..."
        cp -R "${STAGING_DIR}/"* "/Volumes/${VOLUME_NAME}/" 2>/dev/null || true
        cp -R "${STAGING_DIR}/".* "/Volumes/${VOLUME_NAME}/" 2>/dev/null || true
        
        """
        
        if let iconPath = project.volumeIconPath, !iconPath.isEmpty {
            script += """
            # Setup Volume Icon on mounted volume
            if [ -f "\(iconPath)" ]; then
                cp "\(iconPath)" "/Volumes/${VOLUME_NAME}/.VolumeIcon.icns" 2>/dev/null || true
                SetFile -c icnC "/Volumes/${VOLUME_NAME}/.VolumeIcon.icns" 2>/dev/null || true
                SetFile -a V "/Volumes/${VOLUME_NAME}/.VolumeIcon.icns" 2>/dev/null || true
                SetFile -a C "/Volumes/${VOLUME_NAME}" 2>/dev/null || true
            fi
            
            """
        }
        
        script += """
        # 6. Apply Finder Window & Icon Layout styling via AppleScript
        echo "✨ Applying Finder window layout..."
        osascript << 'APPLESCRIPT_EOF'
        \(appleScript)
        APPLESCRIPT_EOF
        
        # Sync and wait for Finder .DS_Store flush
        sync
        sleep 2
        
        # 7. Detach temporary volume
        echo "⏏️ Unmounting volume..."
        hdiutil detach "/Volumes/${VOLUME_NAME}" -force
        
        # 8. Convert to compressed target format (UDZO)
        mkdir -p "${OUTPUT_DIR}"
        FINAL_PATH="${OUTPUT_DIR}/${FINAL_DMG}"
        rm -f "${FINAL_PATH}"
        
        echo "📦 Converting to final compressed DMG (UDZO zlib)..."
        hdiutil convert "${TEMP_DMG}" -format "\(format)" -imagekey zlib-level=\(level) -o "${FINAL_PATH}"
        """
        
        if let iconPath = project.volumeIconPath, !iconPath.isEmpty {
            script += """
            
            # Set custom icon bit on DMG file
            SetFile -a C "${FINAL_PATH}" 2>/dev/null || true
            """
        }
        
        // Code signing
        if project.codeSigningEnabled && !project.signingIdentity.isEmpty {
            script += """
            
            # 9. Code Signing DMG
            echo "🔏 Signing DMG with identity '\(project.signingIdentity)'..."
            codesign --force --sign "\(project.signingIdentity)" --timestamp "${FINAL_PATH}"
            codesign --verify --verbose=2 "${FINAL_PATH}"
            """
        }
        
        // Notarization
        if project.notarizationEnabled && !project.notarizationProfile.isEmpty {
            script += """
            
            # 10. Notarization
            echo "🛡 Submitting to Apple Notary Service..."
            xcrun notarytool submit "${FINAL_PATH}" --keychain-profile "\(project.notarizationProfile)" --wait
            """
            
            if project.stapleTicket {
                script += """
                
                echo "📎 Stapling notarization ticket..."
                xcrun stapler staple "${FINAL_PATH}"
                """
            }
        }
        
        script += """
        
        
        echo "🎉 DMG Build Succeeded! Exported to: ${FINAL_PATH}"
        """
        
        return script
    }
}
